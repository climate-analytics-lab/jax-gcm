"""ECHAM-HAM's in-cloud impaction look-up tables (HAM2.3, ``mo_ham_wetdep_data``).

The collector and aerosol radius axes and the collision tables that
``mo_ham_wetdep.f90::ic_scav_imp`` interpolates (ECHAM6.3-HAM2.3-MOZ1.0,
r7492). The droplet tables and the plate table were computed by Betty Croft
for ECHAM5-HAM's size-dependent in-cloud scavenging and are documented in
Croft et al. (2010, Atmos. Chem. Phys. 10, 1511-1543), which builds on the
below-cloud tables of Croft et al. (2009, Atmos. Chem. Phys. 9, 4653-4675);
the plate table entered HAM in 2013 (G. Frontoso, C2SM-ETHZ). The numbers
below were read from the compiled r7492 data module (printed by a program
linked against it), not transcribed from its source text, and are exactly
the float64 values that module holds.

Axes, all radii in micrometres:

* ``CAERORAD_UM`` (61) -- aerosol radius. Node ``i >= 1`` is
  ``1e-4 * 2**((i - 1)/3)`` to four significant figures; HAM picks the node
  pair with ``floor(3*log2(1e4*r) + 1)``.
* ``CDROPRAD_UM_R7492`` (11) -- cloud-droplet effective radius, 5 um spacing,
  except that node 6 reads 0.0 where the spacing gives 30.0. The droplet
  tables have rows 0-9 only, so node 10 is never read.
* ``CDROPRAD_UM`` -- the same axis with node 6 at 30 um, the axis jcm uses
  by default (see ``incloud_impaction``).
* ``CPLATERAD_UM`` (35) -- ice-plate radius: 5 um spacing to 50 um, then
  25 um spacing to 650 um.

Tables (row = collector node, column = aerosol node):

* ``SCAVDROPN`` / ``SCAVDROPM`` (10 x 61) -- the fraction of a mode's
  number / mass collected by cloud droplets (dimensionless; HAM uses the
  interpolated value as the in-cloud impaction fraction directly).
* ``SCAVICEPLATE`` (35 x 61) -- the collection kernel of an ice plate in
  cm3 s-1 per crystal; HAM forms the fraction as
  ``1 - exp(-K * 1e-6 * ICNC * dt)`` with ICNC in m-3.

Row 0 of each table (collector radius 0) is all zeros.
"""

