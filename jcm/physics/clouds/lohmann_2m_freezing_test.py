def _closure_tendencies():
    """Run cloud_microphysics_2m on the supercooled fixture columns WITHOUT freezing_aerosol,
    float64, jcm's own constants and default CloudParams2M except ``ccsaut = 900``, the
    value the reference was generated with, so the closure is compared at fixed
    parameters (dt720 inputs).
    """
    from jcm.physics.clouds.lohmann_2m.scheme import cloud_microphysics_2m
    from jcm.physics.clouds.lohmann_2m_params import CloudParams2M
    import jcm.constants as c
    with np.load(FRZ_REF) as z:
        d = {k[3:]: z[k] for k in z.files if k.startswith("in/")}
        rho = z["diag/dt720/rho"]
    dt = 720.0
    p = CloudParams2M.default(ccsaut=900.0)
    dz = np.diff(d["paphm1"], axis=0) / (rho * c.grav)

    def one(T, q, qc, qi, qnc, qni, cf, r, dz_, tke, pr):
        zero = jnp.zeros_like(T)
        return cloud_microphysics_2m(T, q, pr, qc, qi, qnc, qni, cf, r, dz_, tke, zero, zero,
                                     zero, jnp.asarray(dt, T.dtype), p)[0]

    args = [d["ptm1"], d["pqm1"], d["pxlm1"], d["pxim1"], d["xtm1_cdnc"], d["xtm1_icnc"],
            d["paclc"], rho, dz, d["ptkem1"], d["papm1"]]
    with jax.enable_x64(True):
        t = jax.vmap(one, in_axes=1, out_axes=1)(*[jnp.asarray(x, jnp.float64) for x in args])
        return {k: np.asarray(getattr(t, k)) for k in TEND_FIELDS}


def test_aerosol_free_closure_unchanged():
    """Without freezing_aerosol the scheme computes what dev 2dc609fd computed, to
    round-off, in supercooled cells where the DeMott closure freezes droplets.
    """
    ref = np.load(CLOSURE_REF)
    got = _closure_tendencies()
    assert np.max(np.abs(ref["dqnidt"])) > 0.0
    for k in TEND_FIELDS:
        np.testing.assert_allclose(got[k], ref[k], rtol=1e-12,
                                   atol=1e-12 * float(np.max(np.abs(ref[k]))), err_msg=k)


